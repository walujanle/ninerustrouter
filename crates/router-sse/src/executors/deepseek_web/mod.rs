/// Apply the fingerprint headers plus the extras this call needs.
fn base_headers(extra: &[(&str, String)]) -> HeaderMap {
    let mut headers = HeaderMap::new();
    for (name, value) in FINGERPRINT_HEADERS {
        let _ = insert_header(&mut headers, name, value);
    }
    for (name, value) in extra {
        let _ = insert_header(&mut headers, name, value);
    }
    headers
}

/// POST a JSON body and read the JSON answer.
async fn post_json(
    url: &str,
    headers: HeaderMap,
    body: &Value,
    proxy_options: &ProxyOptions,
) -> Result<(u16, Value), ExecError> {
    let target = prepare_send(url, proxy_options)
        .await
        .map_err(|e| ExecError::Build(e.to_string()))?;
    let mut builder = target
        .client
        .post(&target.url)
        .timeout(AUX_TIMEOUT)
        .body(serde_json::to_vec(body).map_err(|e| ExecError::Build(e.to_string()))?);
    for (name, value) in headers.iter() {
        builder = builder.header(name, value);
    }
    for (name, value) in &target.extra_headers {
        builder = builder.header(name.as_str(), value.as_str());
    }
    let response = builder.send().await.map_err(ExecError::Request)?;
    let status = response.status().as_u16();
    let text = response.text().await.map_err(ExecError::Request)?;
    let parsed = serde_json::from_str::<Value>(&text).unwrap_or(Value::Null);
    Ok((status, parsed))
}

/// `acquireAccessToken`: exchange the `userToken` for a short-lived token.
async fn acquire_access_token(
    user_token: &str,
    proxy_options: &ProxyOptions,
) -> Result<String, String> {
    let now = (crate::session_manager::now_ms() / 1000) as i64;
    if let Some(cached) = TOKEN_CACHE.get(user_token)
        && cached.expires_at > now
    {
        return Ok(cached.access_token.clone());
    }

    let headers = base_headers(&[("Authorization", format!("Bearer {user_token}"))]);
    let (status, json) = post_json(
        &format!("{API_BASE}/v0/users/current"),
        headers,
        &json!({}),
        proxy_options,
    )
    .await
    .map_err(|e| format!("users/current failed: {e}"))?;

    if status == http_status::UNAUTHORIZED || status == http_status::FORBIDDEN {
        return Err(
            "Token invalid or expired — get a new userToken from DeepSeek localStorage".to_string(),
        );
    }
    if !(200..300).contains(&status) {
        return Err(format!("users/current HTTP {status}"));
    }
    if let Some(code) = json.get("code").and_then(Value::as_i64)
        && code != 0
    {
        TOKEN_CACHE.remove(user_token);
        let message = json
            .get("msg")
            .or_else(|| json.get("data").and_then(|d| d.get("biz_msg")))
            .and_then(Value::as_str)
            .map(str::to_string)
            .unwrap_or_else(|| format!("error code {code}"));
        return Err(format!("DeepSeek rejected token: {message}"));
    }

    let biz =
        biz_data(&json).ok_or_else(|| "Failed to acquire token: Unknown error".to_string())?;
    let access_token = biz
        .get("token")
        .and_then(Value::as_str)
        .filter(|s| !s.is_empty())
        .ok_or_else(|| "Failed to acquire token: no token in response".to_string())?
        .to_string();

    evict_oldest(&TOKEN_CACHE);
    TOKEN_CACHE.insert(
        user_token.to_string(),
        CachedToken {
            access_token: access_token.clone(),
            expires_at: now + TOKEN_TTL_SECS,
        },
    );
    Ok(access_token)
}

/// `json?.data?.biz_data || json?.biz_data`.
fn biz_data(json: &Value) -> Option<&Value> {
    json.get("data")
        .and_then(|d| d.get("biz_data"))
        .or_else(|| json.get("biz_data"))
        .filter(|v| v.is_object())
}

/// `createSession(accessToken)`: a fresh upstream chat session id.
async fn create_session(
    access_token: &str,
    proxy_options: &ProxyOptions,
) -> Result<String, String> {
    let headers = base_headers(&[
        ("Authorization", format!("Bearer {access_token}")),
        ("Cookie", fake_cookie()),
    ]);
    let (status, json) = post_json(
        &format!("{API_BASE}/v0/chat_session/create"),
        headers,
        &json!({}),
        proxy_options,
    )
    .await
    .map_err(|e| format!("chat_session/create failed: {e}"))?;
    if !(200..300).contains(&status) {
        return Err(format!("chat_session/create HTTP {status}"));
    }
    biz_data(&json)
        .and_then(|b| b.get("chat_session"))
        .and_then(|s| s.get("id"))
        .and_then(Value::as_str)
        .map(str::to_string)
        .ok_or_else(|| {
            format!(
                "No session id: code={}",
                json.get("code").and_then(Value::as_i64).unwrap_or(0)
            )
        })
}

/// Best-effort cleanup of an upstream session.
async fn delete_session(access_token: &str, session_id: &str, proxy_options: &ProxyOptions) {
    let headers = base_headers(&[("Authorization", format!("Bearer {access_token}"))]);
    let _ = post_json(
        &format!("{API_BASE}/v0/chat_session/delete"),
        headers,
        &json!({ "chat_session_id": session_id }),
        proxy_options,
    )
    .await;
}

/// The PoW challenge the endpoint hands out.
pub struct PowChallenge {
    pub algorithm: String,
    pub challenge: String,
    pub salt: String,
    pub signature: String,
    pub target_path: String,
    pub difficulty: u32,
    pub expire_at: i64,
}

/// `requestDeepSeekPowChallenge`.
async fn request_pow_challenge(
    access_token: &str,
    proxy_options: &ProxyOptions,
) -> Result<PowChallenge, String> {
    let target_path = "/api/v0/chat/completion";
    let headers = base_headers(&[("Authorization", format!("Bearer {access_token}"))]);
    let (status, json) = post_json(
        &format!("{API_BASE}/v0/chat/create_pow_challenge"),
        headers,
        &json!({ "target_path": target_path }),
        proxy_options,
    )
    .await
    .map_err(|e| format!("create_pow_challenge failed: {e}"))?;
    if !(200..300).contains(&status) {
        return Err(format!("create_pow_challenge HTTP {status}"));
    }

    let challenge = json
        .get("data")
        .and_then(|d| d.get("biz_data"))
        .or_else(|| json.get("biz_data"))
        .and_then(|b| b.get("challenge"))
        .ok_or_else(|| "Invalid DeepSeek PoW challenge".to_string())?;

    let algorithm = challenge.get("algorithm").and_then(Value::as_str);
    let digest = challenge.get("challenge").and_then(Value::as_str);
    let salt = challenge.get("salt").and_then(Value::as_str);
    let signature = challenge.get("signature").and_then(Value::as_str);
    let difficulty = challenge.get("difficulty").and_then(Value::as_i64);
    let expire_at = challenge.get("expire_at").and_then(Value::as_i64);

    let (
        Some(algorithm),
        Some(digest),
        Some(salt),
        Some(signature),
        Some(difficulty),
        Some(expire_at),
    ) = (algorithm, digest, salt, signature, difficulty, expire_at)
    else {
        return Err("Invalid DeepSeek PoW challenge".to_string());
    };
    if digest.len() != 64 || !digest.chars().all(|c| c.is_ascii_hexdigit()) {
        return Err(
            "DeepSeek PoW challenge must be a 64-character SHA3-256 hex digest".to_string(),
        );
    }
    if salt.is_empty() || salt.len() > 1024 {
        return Err("DeepSeek PoW salt must contain 1-1024 characters".to_string());
    }
    if !(1..=i64::from(MAX_DIFFICULTY)).contains(&difficulty) {
        return Err(format!(
            "DeepSeek PoW difficulty must be an integer from 1 to {MAX_DIFFICULTY}"
        ));
    }
    if expire_at < 0 {
        return Err("DeepSeek PoW expiry must be a non-negative safe integer".to_string());
    }

    Ok(PowChallenge {
        algorithm: algorithm.to_string(),
        challenge: digest.to_lowercase(),
        salt: salt.to_string(),
        signature: signature.to_string(),
        target_path: target_path.to_string(),
        difficulty: difficulty as u32,
        expire_at,
    })
}

/// `solvePow`: the base64 header value the endpoint expects.
pub fn solve_pow(challenge: &PowChallenge) -> Result<String, String> {
    let digest = hex_to_bytes(&challenge.challenge)
        .ok_or_else(|| "PoW challenge is not valid hex".to_string())?;
    let prefix = format!("{}_{}_", challenge.salt, challenge.expire_at);
    let answer = pow::find_nonce(&prefix, &digest, challenge.difficulty)
        .ok_or_else(|| "PoW solver failed".to_string())?;
    let payload = json!({
        "algorithm": challenge.algorithm,
        "challenge": challenge.challenge,
        "salt": challenge.salt,
        "answer": answer,
        "signature": challenge.signature,
        "target_path": challenge.target_path,
    });
    use base64::Engine;
    Ok(base64::engine::general_purpose::STANDARD.encode(payload.to_string()))
}

/// Decode a lower-case hex digest.
fn hex_to_bytes(hex: &str) -> Option<[u8; 32]> {
    if hex.len() != 64 {
        return None;
    }
    let mut out = [0u8; 32];
    for (i, byte) in out.iter_mut().enumerate() {
        *byte = u8::from_str_radix(&hex[i * 2..i * 2 + 2], 16).ok()?;
    }
    Some(out)
}

/// The `{status, message}` a `parse_error` produces for a DeepSeek envelope.
fn parse_deepseek_error(status: u16, parsed: &Value) -> Option<(u16, String, Option<i64>)> {
    let code = parsed.get("code").and_then(Value::as_i64)?;
    if code == 0 {
        return None;
    }
    let message = parsed
        .get("msg")
        .or_else(|| parsed.get("data").and_then(|d| d.get("biz_msg")))
        .and_then(Value::as_str)
        .map(str::to_string)
        .unwrap_or_else(|| format!("DeepSeek error {code}"));
    let mapped = if code == 40003 {
        http_status::UNAUTHORIZED
    } else if code == 40002 {
        http_status::RATE_LIMITED
    } else {
        http_status::BAD_GATEWAY
    };
    let _ = status;
    Some((mapped, message, Some(code)))
}

#[async_trait]
impl Executor for DeepSeekWebExecutor {
    fn provider(&self) -> &str {
        self.inner.provider()
    }

    fn config(&self) -> &Transport {
        self.inner.config()
    }

    /// The endpoint takes only a flat `prompt` string, so the whole request is
    /// built here rather than translated.
    async fn execute(&self, req: ExecuteRequest<'_>) -> Result<UpstreamResponse, ExecError> {
        let created = crate::session_manager::now_ms() / 1000;
        let client_model = req.model.trim();
        let client_model = if client_model.is_empty() {
            "deepseek-web"
        } else {
            client_model
        };

        // A tool-bearing request is refused outright: see the module header.
        if req
            .body
            .get("tools")
            .and_then(Value::as_array)
            .is_some_and(|tools| !tools.is_empty())
        {
            return self.error(http_status::BAD_REQUEST, "deepseek-web does not translate tool calls. Use a tool-capable provider for this request.");
        }

        let Some(user_token) = extract_user_token(req.credentials) else {
            return self.error(http_status::BAD_REQUEST, "Missing userToken — paste it from DeepSeek localStorage (DevTools -> Application -> Local Storage -> chat.deepseek.com -> userToken)");
        };

        let (model_type, thinking_enabled, search_enabled) =
            resolve_model_options(req.model, &req.body);
        let history_window = req
            .credentials
            .provider_specific_data
            .get("historyWindow")
            .and_then(Value::as_u64)
            .filter(|n| *n > 0)
            .unwrap_or(0) as usize;
        let persist_session = req
            .credentials
            .provider_specific_data
            .get("persistSession")
            .and_then(Value::as_bool)
            == Some(true);

        let messages = req
            .body
            .get("messages")
            .and_then(Value::as_array)
            .cloned()
            .unwrap_or_default();
        let prompt = messages_to_prompt(&messages, history_window);

        if let Some(log) = req.log {
            log.info(
                "DEEPSEEK-WEB",
                &format!(
                    "model_type={model_type}, thinking={thinking_enabled}, search={search_enabled}, stream={}, persist={persist_session}, window={history_window}",
                    req.stream
                ),
            );
        }

        let access_token = match acquire_access_token(&user_token, &req.proxy_options).await {
            Ok(token) => token,
            Err(message) => {
                let status = if message.contains("invalid or expired") {
                    http_status::UNAUTHORIZED
                } else {
                    http_status::BAD_GATEWAY
                };
                return self.error(status, &message);
            }
        };

        // With persistence off (the default) every request gets a fresh session,
        // which sidesteps a session the user deleted in the DeepSeek UI.
        let session_id = if persist_session {
            match SESSION_CACHE.get(&user_token).map(|e| e.value().clone()) {
                Some(cached) => cached,
                None => match create_session(&access_token, &req.proxy_options).await {
                    Ok(id) => {
                        evict_oldest(&SESSION_CACHE);
                        SESSION_CACHE.insert(user_token.clone(), id.clone());
                        id
                    }
                    Err(message) => {
                        return self.error(http_status::BAD_GATEWAY, &message);
                    }
                },
            }
        } else {
            match create_session(&access_token, &req.proxy_options).await {
                Ok(id) => id,
                Err(message) => {
                    return self.error(http_status::BAD_GATEWAY, &message);
                }
            }
        };

        let response = self
            .complete(
                &access_token,
                &session_id,
                &prompt,
                &model_type,
                thinking_enabled,
                search_enabled,
                &req,
                client_model,
                created,
                &user_token,
                persist_session,
            )
            .await;

        if !persist_session {
            delete_session(&access_token, &session_id, &req.proxy_options).await;
        }
        response
    }
}

impl DeepSeekWebExecutor {
    /// One PoW-challenge + completion round trip.
    #[allow(clippy::too_many_arguments)]
    async fn complete(
        &self,
        access_token: &str,
        session_id: &str,
        prompt: &str,
        model_type: &str,
        thinking_enabled: bool,
        search_enabled: bool,
        req: &ExecuteRequest<'_>,
        client_model: &str,
        created: u64,
        user_token: &str,
        persist_session: bool,
    ) -> Result<UpstreamResponse, ExecError> {
        let challenge = match request_pow_challenge(access_token, &req.proxy_options).await {
            Ok(c) => c,
            Err(message) => {
                return self.error(http_status::BAD_GATEWAY, &message);
            }
        };
        let pow_answer = match solve_pow(&challenge) {
            Ok(answer) => answer,
            Err(message) => {
                return self.error(http_status::BAD_GATEWAY, &message);
            }
        };

        // `new Date().getTimezoneOffset() * -60` — the offset in seconds east
        // of UTC. Read from the host clock's zone, matching the browser's.
        let tz_offset = chrono::Local::now().offset().local_minus_utc();
        let headers = base_headers(&[
            ("Authorization", format!("Bearer {access_token}")),
            ("X-Ds-Pow-Response", pow_answer),
            ("X-Client-Timezone-Offset", tz_offset.to_string()),
            ("Cookie", fake_cookie()),
        ]);
        let payload = json!({
            "chat_session_id": session_id,
            "parent_message_id": Value::Null,
            "model_type": model_type,
            "prompt": prompt,
            "ref_file_ids": req.body.get("ref_file_ids").cloned().unwrap_or(json!([])),
            "thinking_enabled": thinking_enabled,
            "search_enabled": search_enabled,
            "preempt": false,
        });

        let target = prepare_send(COMPLETION_URL, &req.proxy_options)
            .await
            .map_err(|e| ExecError::Build(e.to_string()))?;
        let mut builder = target
            .client
            .post(&target.url)
            .body(serde_json::to_vec(&payload).map_err(|e| ExecError::Build(e.to_string()))?);
        for (name, value) in headers.iter() {
            builder = builder.header(name, value);
        }
        for (name, value) in &target.extra_headers {
            builder = builder.header(name.as_str(), value.as_str());
        }
        let response = builder.send().await.map_err(ExecError::Request)?;
        let status = response.status().as_u16();

        if !(200..300).contains(&status) {
            if status == http_status::UNAUTHORIZED || status == http_status::FORBIDDEN {
                TOKEN_CACHE.remove(user_token);
            }
            if persist_session {
                SESSION_CACHE.remove(user_token);
            }
            let body = response.text().await.unwrap_or_default();
            let parsed = serde_json::from_str::<Value>(&body).unwrap_or(Value::Null);
            if let Some((mapped, message, _)) = parse_deepseek_error(status, &parsed) {
                return self.error(mapped, &message);
            }
            let message = match status {
                http_status::UNAUTHORIZED | http_status::FORBIDDEN => {
                    "DeepSeek token expired — get a fresh userToken from localStorage.".to_string()
                }
                http_status::RATE_LIMITED => "DeepSeek rate limited. Wait and retry.".to_string(),
                _ => format!("DeepSeek API error ({status})"),
            };
            return self.error(status, &message);
        }

        // HTTP 200 can still carry a DeepSeek error envelope, and the reply is
        // always SSE whatever the client asked for.
        let content_type = response
            .headers()
            .get("content-type")
            .and_then(|v| v.to_str().ok())
            .unwrap_or("")
            .to_string();
        if content_type.contains("application/json") {
            let body = response.text().await.unwrap_or_default();
            let parsed = serde_json::from_str::<Value>(&body).unwrap_or(Value::Null);
            if let Some((mapped, message, _)) = parse_deepseek_error(status, &parsed) {
                if mapped == http_status::UNAUTHORIZED {
                    TOKEN_CACHE.remove(user_token);
                }
                if persist_session {
                    SESSION_CACHE.remove(user_token);
                }
                return self.error(mapped, &message);
            }
            return Ok(UpstreamResponse {
                status: 200,
                headers: json_headers(),
                body: UpstreamBody::Buffered(Bytes::from(body)),
                url: COMPLETION_URL.to_string(),
                request_headers: HeaderMap::new(),
            });
        }

        use futures::StreamExt;
        let chunks = response
            .bytes_stream()
            .map(|r| r.map_err(std::io::Error::other));

        if req.stream {
            let stream_id = format!("chatcmpl-{created}-{}", uuid::Uuid::new_v4().simple());
            let body = transform_stream(
                Box::pin(chunks),
                client_model.to_string(),
                stream_id,
                created,
            );
            return Ok(UpstreamResponse {
                status: 200,
                headers: sse_headers(),
                body: UpstreamBody::Synthesized(body),
                url: COMPLETION_URL.to_string(),
                request_headers: HeaderMap::new(),
            });
        }

        let collected = collect_completion(Box::pin(chunks)).await;
        // A body that stopped without `response/status: FINISHED` is a dropped
        // session, not a short answer. Reporting partial text as `stop` would
        // hide it.
        if !collected.saw_finished && collected.content.is_empty() {
            return self.error(http_status::BAD_GATEWAY, "DeepSeek web session ended before completion (no FINISHED signal received) — likely a dropped cookie session. Retry the request.");
        }
        let body = completion_body(client_model, &collected, created);
        Ok(UpstreamResponse {
            status: 200,
            headers: json_headers(),
            body: UpstreamBody::Buffered(Bytes::from(body.to_string())),
            url: COMPLETION_URL.to_string(),
            request_headers: HeaderMap::new(),
        })
    }

    /// Build a JSON error response. The `errorCode` the endpoint returns is
    /// folded into the message by the caller, so it is not carried separately.
    fn error(&self, status: u16, message: &str) -> Result<UpstreamResponse, ExecError> {
        let body = failure(status, message, None);
        Ok(UpstreamResponse {
            status,
            headers: json_headers(),
            body: UpstreamBody::Buffered(Bytes::from(body.to_string())),
            url: COMPLETION_URL.to_string(),
            request_headers: HeaderMap::new(),
        })
    }
}

fn json_headers() -> HeaderMap {
    let mut headers = HeaderMap::new();
    let _ = insert_header(&mut headers, "Content-Type", "application/json");
    headers
}

/// `SSE_HEADERS_NO_BUFFER`: the endpoint sits behind nginx, which otherwise
/// holds the stream until the response completes.
fn sse_headers() -> HeaderMap {
    let mut headers = HeaderMap::new();
    let _ = insert_header(&mut headers, "Content-Type", "text/event-stream");
    let _ = insert_header(&mut headers, "Cache-Control", "no-cache");
    let _ = insert_header(&mut headers, "X-Accel-Buffering", "no");
    headers
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::credentials::Credentials;

    #[test]
    fn a_json_wrapped_token_is_unwrapped() {
        let credentials = Credentials {
            api_key: Some(r#"{"value":"tok-123"}"#.into()),
            ..Default::default()
        };
        assert_eq!(
            extract_user_token(&credentials),
            Some("tok-123".to_string())
        );

        let credentials = Credentials {
            api_key: Some("raw-token".into()),
            ..Default::default()
        };
        assert_eq!(
            extract_user_token(&credentials),
            Some("raw-token".to_string())
        );

        // Falls through to the access token, then gives up.
        let credentials = Credentials {
            access_token: Some("access".into()),
            ..Default::default()
        };
        assert_eq!(extract_user_token(&credentials), Some("access".to_string()));
        assert_eq!(extract_user_token(&Credentials::default()), None);
    }

    #[test]
    fn the_pow_header_is_base64_of_the_challenge_envelope() {
        let challenge = PowChallenge {
            algorithm: "DeepSeekHashV1".into(),
            challenge: "eb1554b3f98c63cde3da0be54e8e8d6f0328c6a78ebb096aad42b9d406546c45".into(),
            salt: "salt".into(),
            signature: "sig".into(),
            target_path: "/api/v0/chat/completion".into(),
            difficulty: 1_000_000,
            expire_at: 1_700_000_000,
        };
        let answer = solve_pow(&challenge).expect("the vector is satisfiable");
        use base64::Engine;
        let decoded = base64::engine::general_purpose::STANDARD
            .decode(answer)
            .expect("base64");
        let parsed: Value = serde_json::from_slice(&decoded).expect("json");
        assert_eq!(parsed["answer"], json!(0));
        assert_eq!(parsed["algorithm"], json!("DeepSeekHashV1"));
        assert_eq!(parsed["target_path"], json!("/api/v0/chat/completion"));
    }

    #[test]
    fn a_non_hex_challenge_is_rejected() {
        let challenge = PowChallenge {
            algorithm: "DeepSeekHashV1".into(),
            challenge: "zz".into(),
            salt: "salt".into(),
            signature: "sig".into(),
            target_path: "/api/v0/chat/completion".into(),
            difficulty: 10,
            expire_at: 1,
        };
        assert!(solve_pow(&challenge).is_err());
    }

    #[test]
    fn deepseek_error_codes_map_to_http_statuses() {
        let (status, message, code) =
            parse_deepseek_error(200, &json!({"code": 40003, "msg": "expired"})).unwrap();
        assert_eq!(status, http_status::UNAUTHORIZED);
        assert_eq!(message, "expired");
        assert_eq!(code, Some(40003));

        let (status, _, _) =
            parse_deepseek_error(200, &json!({"code": 40002, "msg": "slow down"})).unwrap();
        assert_eq!(status, http_status::RATE_LIMITED);

        let (status, _, _) = parse_deepseek_error(200, &json!({"code": 7, "msg": "boom"})).unwrap();
        assert_eq!(status, http_status::BAD_GATEWAY);

        // code 0 is success, not an error.
        assert!(parse_deepseek_error(200, &json!({"code": 0})).is_none());
        assert!(parse_deepseek_error(200, &json!({"ok": true})).is_none());
    }

    #[test]
    fn biz_data_reads_both_envelope_shapes() {
        assert_eq!(
            biz_data(&json!({"data": {"biz_data": {"token": "t"}}}))
                .and_then(|b| b.get("token"))
                .and_then(Value::as_str),
            Some("t")
        );
        assert_eq!(
            biz_data(&json!({"biz_data": {"token": "t"}}))
                .and_then(|b| b.get("token"))
                .and_then(Value::as_str),
            Some("t")
        );
        assert!(biz_data(&json!({"data": {}})).is_none());
    }

    #[test]
    fn the_executor_reads_the_registry_entry() {
        let executor = DeepSeekWebExecutor::new();
        assert_eq!(executor.provider(), "deepseek-web");
        assert_eq!(executor.config().base_url.as_deref(), Some(COMPLETION_URL));
    }
}
