//! The `deepseek-web` executor: chat.deepseek.com's own web API.
//!
//! Four calls, in order, per request: the `userToken` from the browser's
//! localStorage is exchanged for a short-lived access token at
//! `/api/v0/users/current`, a chat session is created, a DeepSeekHashV1
//! proof-of-work challenge is solved, and the completion is streamed back.
//!
//! Two ceilings are deliberate:
//!
//! * **No tool-call translation.** Upstream's tool layer (`deepseekWebTools.js`
//!   plus `deepseekWebToolBinding.js`) is over a thousand lines of prompt
//!   serialization and reply parsing. A request carrying `tools[]` is answered
//!   with an explicit `400` naming the limitation rather than silently dropping
//!   the tools, which would hand the client a plain-text answer where it
//!   expected a call. `ponytail:` to lift this, port those two modules and call
//!   them in `execute` before the completion; the prompt builder and the SSE
//!   transform here are already tool-agnostic.
//! * **No `x-hif-leim`.** The live web client also sends a signed client
//!   attestation header generated by obfuscated JS. Upstream omits it too, and
//!   the completion endpoint does not currently enforce it. If that changes,
//!   the header has to come from a real browser session.

